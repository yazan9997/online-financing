def send_request_to_admin(request_type: str, customer_name: str, rows: list, attachments: dict):
    """
    إرسال بيانات الطلب والمرفقات مباشرة إلى بريد الإدارة عبر SMTP.

    rows: قائمة من (label, value) تمثل بيانات الطلب.
    attachments: قاموس {اسم الفئة: كائن UploadedFile من Streamlit أو None}.
                 يُقرأ محتوى الملف مباشرة من الذاكرة (getvalue) دون أي كتابة على القرص.
    """
    admin_email, sender_email, sender_password = get_mail_config()

    if not admin_email or not sender_email or not sender_password:
        return False, (
            "⚠️ لم يتم ضبط إعدادات البريد الإلكتروني الخاصة بالإدارة بعد. "
            "يرجى إضافة بيانات الاعتماد في ملف الأسرار (secrets) الخاص بالتطبيق."
        )

    try:
        msg = MIMEMultipart()
        msg["From"] = sender_email
        msg["To"] = admin_email
        msg["Subject"] = Header(f"🔔 طلب جديد: {request_type} - {customer_name}", "utf-8")

        body_lines = [
            "البنك الإسلامي الفلسطيني",
            "=" * 50,
            "تم استلام طلب جديد عبر الموقع الإلكتروني.",
            "",
            f"نوع الطلب: {request_type}",
            f"اسم العميل: {customer_name}",
            "",
            "بيانات الطلب:",
            "-" * 50,
        ]
        for label, value in rows:
            body_lines.append(f"{label}: {value}")

        body_lines.extend(["", "المرفقات:", "-" * 50])

        attachment_count = 0
        for category, files in attachments.items():
            if not files:
                continue
            file_list = files if isinstance(files, list) else [files]
            for f in file_list:
                if f is not None:
                    body_lines.append(f"- {category}: {f.name}")
                    attachment_count += 1

        if attachment_count == 0:
            body_lines.append("لا توجد مرفقات.")

        body_lines.extend([
            "",
            "ملاحظة أمنية: تم إرسال هذه البيانات والمرفقات مباشرة عبر البريد الإلكتروني "
            "ولم يتم حفظ أي نسخة منها على خوادم الموقع.",
            "",
            "يرجى مراجعة الطلب والتواصل مع العميل حسب الإجراءات المعتمدة.",
        ])

        msg.attach(MIMEText("\n".join(body_lines), "plain", "utf-8"))

        # إرفاق الملفات مباشرة من الذاكرة (بدون أي حفظ مؤقت على القرص)
        for category, files in attachments.items():
            file_list = files if isinstance(files, list) else [files]
            for f in file_list:
                if f is None:
                    continue
                file_bytes = f.getvalue()  # قراءة من الذاكرة مباشرة
                part = MIMEApplication(file_bytes, _subtype="octet-stream")
                part.add_header("Content-Disposition", "attachment", filename=("utf-8", "", f.name))
                part.add_header("X-Attachment-Category", category)
                msg.attach(part)

        with smtplib.SMTP("smtp.gmail.com", 587, timeout=30) as server:
            server.starttls()
            server.login(sender_email, sender_password)
            server.sendmail(sender_email, admin_email, msg.as_string())

        return True, "📩 تم إرسال طلبك بنجاح إلى إدارة البنك. سيتم التواصل معك قريباً."

    except Exception as e:
        return False, f"❌ تعذر إرسال الطلب عبر البريد الإلكتروني: {e}"


