def page_calculator():
    st.markdown("## 🧮 حاسبة التمويل والأقساط")
    st.markdown("<div class='gold-divider'></div>", unsafe_allow_html=True)

    with st.container():
        st.markdown("<div class='section-box'>", unsafe_allow_html=True)
        purpose_label = st.selectbox(
            "غرض التمويل",
            options=[v["label"] for v in FINANCING_PURPOSES.values()],
            key="calc_purpose",
        )
        purpose_key = [k for k, v in FINANCING_PURPOSES.items() if v["label"] == purpose_label][0]
        purpose_info = FINANCING_PURPOSES[purpose_key]
        max_years, profit_rate = purpose_info["max_years"], purpose_info["profit_rate"]

        c1, c2 = st.columns(2)
        amount = c1.number_input("قيمة التمويل المطلوب (₪)", min_value=0.0, step=500.0, key="calc_amount")
        down = c2.number_input("الدفعة المقدمة (₪)", min_value=0.0, step=500.0, key="calc_down")

        c3, c4, c5 = st.columns(3)
        salary = c3.number_input("الراتب الأساسي الشهري (₪)", min_value=0.0, step=100.0, key="calc_salary")
        extra = c4.number_input("الدخل الإضافي الشهري (₪)", min_value=0.0, step=100.0, key="calc_extra")
        commitments = c5.number_input("الالتزامات الشهرية الحالية (₪)", min_value=0.0, step=100.0, key="calc_commit")

        calc_clicked = st.button("احسب الأقساط", use_container_width=True)
        st.markdown("</div>", unsafe_allow_html=True)

    if calc_clicked:
        if down >= amount:
            st.error("❌ يجب أن تكون الدفعة المقدمة أقل من قيمة التمويل.")
        elif (salary + extra) <= 0:
            st.error("❌ إجمالي الدخل يجب أن يكون أكبر من صفر.")
        else:
            net = amount - down
            income = salary + extra
            st.info(
                f"**الغرض:** {purpose_key} | **نسبة الربح السنوية:** {profit_rate}% | "
                f"**صافي التمويل:** ₪{net:,.2f} | **إجمالي الدخل:** ₪{income:,.2f}"
            )
            schedule = build_schedule(net, income, commitments, max_years, profit_rate)
            st.dataframe(schedule, use_container_width=True, hide_index=True)
            st.session_state["prefill_purpose"] = purpose_key
            st.session_state["prefill_amount"] = amount
            st.session_state["prefill_down"] = down
            st.session_state["prefill_salary"] = salary
            st.session_state["prefill_extra"] = extra
            st.session_state["prefill_commit"] = commitments
            st.button("📝 تقديم طلب تمويل الآن بهذه البيانات", on_click=go_to, args=("loan_form",))

    render_footer()


