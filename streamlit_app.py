def _load_price_quote_pdf_bytes():
    with open(PRICE_QUOTE_PDF_PATH, "rb") as f:
        return f.read()


def page_price_quote():
    st.markdown("## 💲 عرض السعر")
    st.markdown("<div class='gold-divider'></div>", unsafe_allow_html=True)
    st.markdown(
        "<div class='section-box'>يحتوي هذا الملف على النماذج الرسمية لعروض أسعار الشراء "
        "المعتمدة لدى البنك الإسلامي الفلسطيني: عرض سعر شراء مركبة، عرض سعر شراء عقارات/أراضي، "
        "وعرض سعر شراء بضائع.</div>",
        unsafe_allow_html=True,
    )

    try:
        pdf_bytes = _load_price_quote_pdf_bytes()
    except Exception:
        st.error("⚠️ تعذر إيجاد ملف عرض السعر. تأكد من وجود الملف داخل مجلد assets.")
        render_footer()
        return

    st.download_button(
        "⬇️ تحميل ملف عرض السعر (PDF)",
        data=pdf_bytes,
        file_name="عرض_سعر_شراء.pdf",
        mime="application/pdf",
        use_container_width=True,
    )

    b64_pdf = base64.b64encode(pdf_bytes).decode("utf-8")
    st.markdown(
        f"""
        <iframe src="data:application/pdf;base64,{b64_pdf}"
                width="100%" height="900" style="border:1px solid #eee7d3; border-radius:12px;">
        </iframe>
        """,
        unsafe_allow_html=True,
    )

    render_footer()


